// Package codegen generates typed contract clients from a decoded interface.
//
// The registry already holds everything a generator needs: types are
// recursive and fully resolved, and user-defined types are referenced by
// name. Generating from the stored ABI, rather than from the WASM, means a
// client can be produced for any registered contract — including a
// superseded version, by hash — without touching the network.
package codegen

import (
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/soroworks/sorovault/internal/model"
)

// Source identifies the contract a client is generated for. It is written
// into the file header and exported as constants, so a generated file says
// exactly which interface version it was built from.
type Source struct {
	ContractID string
	Network    string
	WasmHash   string
}

// sdkImport is the module the generated code builds on. Its contract.Client
// fetches the contract spec from the network and creates one method per
// function; the generated Client interface types those methods.
const sdkImport = "@stellar/stellar-sdk/contract"

// reservedTypeNames are identifiers the generated file declares or imports
// itself, plus TypeScript globals a contract type would shadow. A
