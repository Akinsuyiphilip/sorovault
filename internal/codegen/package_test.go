// generatedFile returns one file from a generated package.
func generatedFile(t *testing.T, files []codegen.File, path string) []byte {
	t.Helper()
	for _, file := range files {
		if file.Path == path {
			return file.Data
		}
	}
	t.Fatalf("no generated file %s", path)
	return nil
}

func TestPackageVersion(t *testing.T) {
	t.Parallel()

	tests := []struct {
		in   string
		want string
	}{
		{"abc123", "0.0.0-abc123"},
		{"c618dae264864ccf446a3c7db27da80c7c83e840131242cc2fe9cd32a2a20781", "0.0.0-c618dae26486"},
		{"C618DAE26486", "0.0.0-c618dae26486"},
		{"", "0.0.0"},
		{"---", "0.0.0"},
	}

	for _, tt := range tests {
		assert.Equal(t, tt.want, codegen.PackageVersion(tt.in), tt.in)
	}
}

func TestPackageWritesAPublishableManifest(t *testing.T) {
	t.Parallel()

	iface := &model.Interface{Functions: []model.Function{{Name: "ping"}}}
	files, err := codegen.Package(iface, src, codegen.PackageOptions{Name: "@acme/zkvote"})
	require.NoError(t, err)

	var manifest struct {
		Name             string            `json:"name"`
		Version          string            `json:"version"`
		Type             string            `json:"type"`
		Main             string            `json:"main"`
		Types            string            `json:"types"`
		Files            []string          `json:"files"`
		Scripts          map[string]string `json:"scripts"`
		PeerDependencies map[string]string `json:"peerDependencies"`
		DevDependencies  map[string]string `json:"devDependencies"`
	}
	require.NoError(t, json.Unmarshal(generatedFile(t, files, "package.json"), &manifest))

	assert.Equal(t, "@acme/zkvote", manifest.Name)
	assert.Equal(t, "0.0.0-abc123", manifest.Version, "the default version comes from the WASM hash")
	assert.Equal(t, "module", manifest.Type)
	assert.Equal(t, "dist/index.js", manifest.Main)
	assert.Equal(t, "dist/index.d.ts", manifest.Types)
	assert.Equal(t, "tsc", manifest.Scripts["build"])
	assert.Contains(t, manifest.Files, "dist")

	// The SDK and buffer are peer dependencies, and the dev dependencies pin
	// exactly the versions the golden client is type-checked against, so the
	// package builds without asking the user to guess.
	pinnedRaw, err := os.ReadFile("testdata/package.json")
	require.NoError(t, err)
	var pinned struct {
		DevDependencies map[string]string `json:"devDependencies"`
	}
	require.NoError(t, json.Unmarshal(pinnedRaw, &pinned))

	for _, dep := range []string{"@stellar/stellar-sdk", "buffer"} {
		assert.Equal(t, pinned.DevDependencies[dep], manifest.PeerDependencies[dep], dep)
		assert.NotEmpty(t, manifest.PeerDependencies[dep], "%s must be a peer dependency", dep)
	}
	assert.Equal(t, pinned.DevDependencies["typescript"], manifest.DevDependencies["typescript"])

	client := string(generatedFile(t, files, "src/index.ts"))
	assert.Contains(t, client, "Code generated by SoroVault")
	assert.Contains(t, client, "export interface Client")

	tsconfig := string(generatedFile(t, files, "tsconfig.json"))
	assert.Contains(t, tsconfig, `"outDir": "dist"`)
	assert.Contains(t, tsconfig, `"include": ["src"]`)

	readme := string(generatedFile(t, files, "README.md"))
	assert.Contains(t, readme, "# @acme/zkvote")
	assert.Contains(t, readme, src.ContractID)
	assert.Contains(t, readme, src.WasmHash)
	assert.Contains(t, readme, "npm install @acme/zkvote")
}

func TestPackageVersionCanBeOverridden(t *testing.T) {
	t.Parallel()

	files, err := codegen.Package(&model.Interface{}, src, codegen.PackageOptions{
		Name:    "zkvote-client",
		Version: "1.4.0",
	})
	require.NoError(t, err)

	var manifest struct {
		Version string `json:"version"`
	}
	require.NoError(t, json.Unmarshal(generatedFile(t, files, "package.json"), &manifest))
	assert.Equal(t, "1.4.0", manifest.Version)

	readme := string(generatedFile(t, files, "README.md"))
	assert.Contains(t, readme, "`1.4.0`")
}

func TestPackageRejectsInvalidInput(t *testing.T) {
	t.Parallel()

	_, err := codegen.Package(&model.Interface{}, src, codegen.PackageOptions{Name: "Not A Package"})
	assert.ErrorContains(t, err, "not a valid npm package name")

	_, err = codegen.Package(&model.Interface{}, src, codegen.PackageOptions{Name: "ok", Version: "v1"})
	assert.ErrorContains(t, err, "not a valid semantic version")

	files, err := codegen.Package(&model.Interface{Functions: []model.Function{{Name: "not-valid"}}}, src,
		codegen.PackageOptions{Name: "ok"})
	require.NoError(t, err)
	assert.Contains(t, string(generatedFile(t, files, "src/index.ts")), `  "not-valid"(options?: sdk.MethodOptions):`)
}

func TestPackagePathsAreRelative(t *testing.T) {
	t.Parallel()

	files, err := codegen.Package(&model.Interface{}, src, codegen.PackageOptions{Name: "@acme/zkvote"})
	require.NoError(t, err)

	for _, file := range files {
		assert.False(t, strings.HasPrefix(file.Path, "@"), "paths are relative to the package root")
	}
}
